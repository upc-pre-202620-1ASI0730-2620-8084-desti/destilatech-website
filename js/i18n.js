const LANG_STORAGE_KEY = "destilatech-lang";
const SUPPORTED_LANGS = ["es", "en"];

function getStoredLang() {
  try {
    const stored = localStorage.getItem(LANG_STORAGE_KEY);
    if (SUPPORTED_LANGS.includes(stored)) return stored;
  } catch (e) {}
  return null;
}

function detectBrowserLang() {
  const browserLang = (navigator.language || "es").slice(0, 2).toLowerCase();
  return SUPPORTED_LANGS.includes(browserLang) ? browserLang : "es";
}

function applyLanguage(lang) {
  if (!SUPPORTED_LANGS.includes(lang)) lang = "es";
  const dict = translations[lang];

  document.documentElement.setAttribute("lang", lang);

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] !== undefined) el.innerHTML = dict[key];
  });

  document.querySelectorAll("[data-i18n-attrs]").forEach((el) => {
    let map;
    try {
      map = JSON.parse(el.getAttribute("data-i18n-attrs"));
    } catch (e) {
      return;
    }
    Object.entries(map).forEach(([attr, key]) => {
      if (dict[key] !== undefined) el.setAttribute(attr, dict[key]);
    });
  });

  document.querySelectorAll(".lang-switch__btn").forEach((btn) => {
    btn.classList.toggle("is-active", btn.dataset.lang === lang);
    btn.setAttribute("aria-pressed", String(btn.dataset.lang === lang));
  });

  try {
    localStorage.setItem(LANG_STORAGE_KEY, lang);
  } catch (e) {}
}

document.addEventListener("DOMContentLoaded", () => {
  const initialLang = getStoredLang() || detectBrowserLang();
  applyLanguage(initialLang);

  document.querySelectorAll(".lang-switch__btn").forEach((btn) => {
    btn.addEventListener("click", () => applyLanguage(btn.dataset.lang));
  });
});